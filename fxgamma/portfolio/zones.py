"""Gamma zones, cost-aware hedge bands and pin risk.

This module answers the question the user asked for by name -- *how sensitive is
each gamma zone* -- and it answers the trader's objection to answering it with a
prettier chart (requirements s4.4).  A zone is only useful if it is (a) defined by
an objective rule on the book's own gamma profile rather than by eyeballing a
picture, and (b) reported in units you can act on: gamma per 1% **inside** the zone,
distance in percent *and* in sigma-days, a touch probability, the expiries
responsible, and whether you are long or short gamma there.

How a zone is defined (the objective rule)
------------------------------------------
1. Sweep the book's ``gamma_1pct`` over spot with :func:`~fxgamma.portfolio.risk.spot_ladder`
   under the *active sticky convention* -- sticky-strike and sticky-delta give
   materially different profiles and the zone list must say which it used.
2. Keep grid nodes where ``|gamma_1pct| >= threshold * max|gamma_1pct|`` (default
   ``threshold = 0.20``).  This is the "material" test, relative to the book's own
   peak rather than to an absolute number that would need a currency.
3. Cut those nodes into **sign-homogeneous contiguous runs**.  A zone that mixes long
   and short gamma has a meaningless average, and the long/short flag is the first
   thing the trader reads, so the sign is part of the definition, not a label
   applied afterwards.
4. Merge same-sign runs separated by a gap narrower than ``merge_pct`` of spot
   (default 0.25%): a strike cluster split by one thin node is one zone, not two.
5. Cut any surviving run at an interior trough that drops below ``split_trough``
   (default 0.60) of the smaller peak either side of it, so two strike clusters
   joined by a shallow saddle report as two zones rather than one wide one whose
   average describes neither.
6. Drop zones whose share of the book's total gross gamma area is below
   ``min_share`` (default 5%).
7. The zone's centre is the ``|gamma|``-weighted centroid, which lands on the strike
   cluster generating it rather than on the arithmetic middle of the interval.

Because the profile is generated by the strikes, steps 2-5 recover exactly the
"contiguous regions of material gamma clustered around strike concentrations" the
contract asks for, without ever needing to cluster strikes directly -- and it stays
correct for a book whose zones are *between* strikes (a short-gamma hole between two
long strikes has no strike of its own).

Distance units (trader W-7)
---------------------------
``sigma_days`` uses ``sigma_ATM / sqrt(252)``: spot travels on trading days.  The
``sqrt(365)`` basis is for the *economics* (the theta bill, see
``signals.richness.daily_breakeven``) and using it for distance would understate the
achievable daily move by 20% and make far strikes look safer than they are.
Touch probability is a first-passage over calendar time and so uses ``sigma sqrt(T)``
with ``T`` in ACT/365 years, which is the option's own measure.
"""
