#: spot travels on trading days -- the basis for distance and probability (W-7)
TRADING_DAYS = 252.0
#: theta is paid on calendar days -- the basis for the breakeven identity (W-7)
CALENDAR_DAYS = 365.0


def sigma_day_pct(sigma: float, basis: float = TRADING_DAYS) -> float:
    """One daily sigma of spot movement, in **percent**.  Distance basis: 252."""
    return 100.0 * float(sigma) / math.sqrt(basis)


def touch_probability(S: float, B: float, T: float, sigma: float,
                      drift: float = 0.0) -> float:
    """P(spot touches level ``B`` at any time before ``T``) under GBM.

    First-passage probability for ``dS/S = drift dt + sigma dW`` (``drift = rd - rf``
    gives the forward measure, which is the right measure for "will I trade in this
    zone before it expires").  With ``x = ln(B/S)`` and ``nu = drift - sigma^2/2``::

        B > S:  N((-x + nu T)/(sigma sqrt T)) + e^{2 nu x / sigma^2} N((-x - nu T)/(sigma sqrt T))
        B < S:  N(( x - nu T)/(sigma sqrt T)) + e^{2 nu x / sigma^2} N(( x + nu T)/(sigma sqrt T))

    Returns 1.0 when the level is already touched, and is capped to [0, 1].

    This is a *touch* probability, not a *finish* probability: it is roughly twice the
    latter for a driftless process, and it is the one that matters for a gamma book
    because you trade the zone when spot gets there, not at the fixing.
    """
    S, B, T, sigma = float(S), float(B), float(T), float(sigma)
    if not (S > 0 and B > 0) or T <= 0.0 or sigma <= 0.0:
        return 1.0 if (S > 0 and B > 0 and abs(math.log(B / S)) < 1e-12) else 0.0
    x = math.log(B / S)
    if abs(x) < 1e-14:
        return 1.0
    nu = float(drift) - 0.5 * sigma * sigma
    sq = sigma * math.sqrt(T)
    N = lambda z: float(gk._norm_cdf(z))            # noqa: E731
    expo = 2.0 * nu * x / (sigma * sigma)
    expo = max(min(expo, 500.0), -500.0)
    if x > 0:
        p = N((-x + nu * T) / sq) + math.exp(expo) * N((-x - nu * T) / sq)
    else:
        p = N((x - nu * T) / sq) + math.exp(expo) * N((x + nu * T) / sq)
    return float(min(max(p, 0.0), 1.0))


